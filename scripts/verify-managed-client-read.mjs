import assert from "node:assert/strict";
import { createJiti } from "jiti";
import path from "node:path";
import { readFileSync } from "node:fs";
const jiti = createJiti(import.meta.url, { alias: { "@": path.resolve("src"), "server-only": path.resolve("node_modules/next/dist/compiled/server-only/empty.js") } });
const { managedClientCourseQuery } = await jiti.import("../src/lib/managed-client-courses.ts");
const injected = "' OR TRUE --";
const query = managedClientCourseQuery(injected);
assert.ok(query.values.includes(injected));
assert.equal(query.text.includes(injected), false);
assert.match(query.text, /WHERE d\."clientId" = \$1/);
assert.match(query.text, /LIMIT 21/);
assert.match(query.text, /LEFT JOIN LATERAL/);
assert.doesNotMatch(query.text, /SELECT \*|partner|commission|password|contractToken|UPDATE |DELETE |INSERT /i);
const cursor = { createdAt: new Date("2027-01-01T00:00:00.000Z"), id: injected };
const next = managedClientCourseQuery("client-1", cursor);
assert.equal(next.values.length, 3);
assert.equal(next.values[2], injected);
const page = readFileSync("src/app/client/accompagnement/page.tsx", "utf8");
assert.match(page, /await requireClient\(\)/);
assert.match(page, /getManagedClientCourses\(client\.id, after\)/);
assert.doesNotMatch(readFileSync("src/lib/managed-client-courses.ts", "utf8"), /\$queryRawUnsafe|unstable_cache|new Map/);
